"""A reproducible virtual survey site. Every value here is SYNTHETIC.

Fields are smooth deterministic functions of position (plus seeded noise), so two
robots sampling the same place see consistent values unless a fault is injected.
"""
from __future__ import annotations

import math
import random
import struct
import zlib

# Survey region (inside the default science profile's mission region).
ORIGIN = (45.1000, -122.2200)
EXTENT_DEG = 0.02


class Site:
    def __init__(self, seed: int = 7):
        self.seed = seed
        self.rng = random.Random(seed)

    def point(self, i: int, n: int, lane: int) -> tuple[float, float]:
        """Lawn-mower survey path: lane offsets keep robots apart but overlapping where useful."""
        f = (i % n) / max(1, n - 1)
        return (round(ORIGIN[0] + 0.004 * lane + 0.002 * math.sin(f * math.pi), 6),
                round(ORIGIN[1] + EXTENT_DEG * f, 6))

    def noise(self, s: float) -> float:
        return self.rng.gauss(0, s)

    def soil_moisture(self, lat, lon):      # % volumetric
        return 22 + 9 * math.sin((lat - ORIGIN[0]) * 900) * math.cos((lon - ORIGIN[1]) * 600)

    def soil_ph(self, lat, lon):
        return 6.4 + 0.6 * math.cos((lon - ORIGIN[1]) * 400)

    def soil_temperature(self, lat, lon):   # degC
        return 11.5 + 1.5 * math.sin((lat - ORIGIN[0]) * 500)

    def air_temperature(self, lat, lon):    # degC
        return 16.0 + 0.8 * math.sin((lon - ORIGIN[1]) * 300)

    def humidity(self, lat, lon):           # %
        return 63 + 5 * math.cos((lat - ORIGIN[0]) * 700)

    def pressure(self, lat, lon):           # hPa
        return 1009.5 - 0.3 * (lat - ORIGIN[0]) * 100


def png(width: int, height: int, seed: int) -> bytes:
    """A small synthetic greyscale PNG (no imaging libraries needed)."""
    rng = random.Random(seed)
    rows = b"".join(b"\x00" + bytes((x * 7 + y * 3 + rng.randrange(40)) % 256 for x in range(width)) for y in range(height))
    def chunk(kind, data):
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 0, 0, 0, 0))
            + chunk(b"tEXt", b"Comment\x00SYNTHETIC image generated by cursiv-sim; not a real photograph")
            + chunk(b"IDAT", zlib.compress(rows, 9)) + chunk(b"IEND", b""))
